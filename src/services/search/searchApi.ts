import { API_ENDPOINTS, MAX_PAGES, USERS_PER_PAGE } from '@constant';
import { baseApi } from '@services';

import type {
    GitHubSearchApiResponse,
    GitHubSearchResponse,
} from './search.types';

/**
 * GitHub user search endpoints.
 *
 * Infinite query keeps fetched pages together as the user scrolls.
 */
export const searchApi = baseApi.injectEndpoints({
    endpoints: (builder) => ({
        /**
         * Searches GitHub users using the supplied query.
         *
         * @param queryArg - The search text.
         * @param pageParam - The page to fetch.
         */
        searchUsers: builder.infiniteQuery<
            GitHubSearchResponse,
            string,
            number
        >({
            query: ({ queryArg, pageParam }) => ({
                url: API_ENDPOINTS.SEARCH_USERS,
                params: {
                    q: queryArg,
                    page: pageParam,
                    per_page: USERS_PER_PAGE,
                },
            }),

            /**
             * Converts each API page to the format used by the UI.
             *
             * @param response - The response from GitHub.
             * @returns The response with normalized user options.
             */
            transformResponse: (
                response: GitHubSearchApiResponse,
            ): GitHubSearchResponse => ({
                totalCount: response.totalCount,
                incompleteResults: response.incompleteResults,
                items: response.items.map(({ id, login, avatarUrl, type }) => ({
                    id,
                    username: login,
                    avatarUrl,
                    userType: type,
                })),
            }),

            infiniteQueryOptions: {
                initialPageParam: 1,

                /**
                 * Stops when the last page is reached or no users remain.
                 */
                getNextPageParam: (lastPage, _allPages, lastPageParam) => {
                    const totalPages = Math.min(
                        Math.ceil(lastPage.totalCount / USERS_PER_PAGE),
                        MAX_PAGES,
                    );

                    if (
                        lastPage.items.length === 0 ||
                        lastPageParam >= totalPages
                    ) {
                        return undefined;
                    }

                    return lastPageParam + 1;
                },
            },
        }),
    }),
});

/** Hook generated by RTK Query for paginated GitHub user search. */
export const { useSearchUsersInfiniteQuery } = searchApi;
